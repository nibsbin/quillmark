//! `text` carries richtext's `contentMediaType`, so it lowers through the
//! shared content path with no backend-side case and surfaces geometry as any
//! content field does. Its literal codec keeps markdown delimiters verbatim.
//!
//! Engine altitude, not `Backend::open`: the sharing spans two links, and the
//! render floor coerces the resting literal string to a content object before
//! the backend classifies it.

#![cfg(feature = "typst")]

use quillmark::{Document, Engine, HitGranularity, LiveSession};
use std::fs;
use tempfile::TempDir;

mod common;

fn text_quill(temp_dir: &TempDir) -> std::path::PathBuf {
    let quill_path = temp_dir.path().join("plain_quill");
    fs::create_dir_all(&quill_path).unwrap();
    fs::write(
        quill_path.join("Quill.yaml"),
        r#"quill:
  name: "plain_quill"
  version: "1.0.0"
  backend: "typst"
  description: "text lowering"

typst:
  plate_file: plate.typ

main:
  body:
    enabled: false
  fields:
    subject:
      type: text
      multiline: true
      default: ""
    tags:
      type: array
      items:
        type: text
        multiline: true
      description: text elements
"#,
    )
    .unwrap();
    // The backend pre-lowers content into the `data` dict; the plate just reads it.
    fs::write(
        quill_path.join("plate.typ"),
        "#import \"@local/quillmark-helper:0.2.0\" as qm\n\
         #set page(width: 612pt, height: 792pt, margin: 72pt)\n\
         #set text(size: 11pt)\n\
         = Doc\n#qm.data.subject\n#for t in qm.data.tags { block(t) }\n",
    )
    .unwrap();
    quill_path
}

/// `text` rests as its literal string, so these author unparsed and ride
/// the floor's coercion.
const SUBJECT: &str = "a *literal* subject with _no_ markup";
const STAR_TAG: &str = "literal *star* tag";

fn session(temp_dir: &TempDir) -> LiveSession {
    let quill = quillmark::quill_from_path(text_quill(temp_dir)).expect("load quill");
    let md = format!(
        "~~~card-yaml\n$quill: plain_quill\n$kind: main\n\
         subject: \"{SUBJECT}\"\ntags:\n  - \"{STAR_TAG}\"\n  - \"second plain tag\"\n~~~\n"
    );
    let parsed = Document::parse(&md).expect("parse").document;
    Engine::new().open(&quill, &parsed, common::test_date()).expect("open")
}

#[test]
fn text_elements_and_scalars_surface_regions() {
    let temp_dir = TempDir::new().unwrap();
    let session = session(&temp_dir);
    let regions = session.regions();

    for (field, len) in [
        ("subject", SUBJECT.chars().count()),
        ("tags.0", STAR_TAG.chars().count()),
        ("tags.1", "second plain tag".chars().count()),
    ] {
        let region = regions
            .iter()
            .find(|r| r.field == field)
            .unwrap_or_else(|| panic!("a text content field surfaces {field:?}: {regions:?}"));
        assert_eq!(
            region.span,
            Some([0, len]),
            "{field:?} spans its whole literal, delimiters counted as content"
        );
    }
    assert!(
        !regions.iter().any(|r| r.field == "tags"),
        "the array itself is not a region key: {regions:?}"
    );
}

#[test]
fn a_text_delimiter_is_one_cluster_under_click_and_caret() {
    let temp_dir = TempDir::new().unwrap();
    let session = session(&temp_dir);
    let region = session
        .regions()
        .into_iter()
        .find(|r| r.field == "tags.0")
        .expect("tags.0 region");

    // Finer than the narrowest glyph at 11pt: a skipped offset is the
    // inversion's, not the probe's.
    const STEP: f32 = 0.25;
    let y = region.rect[3] - 3.0;
    let mut walk: Vec<usize> = Vec::new();
    let mut x = region.rect[0];
    while x <= region.rect[2] {
        if let Some(hit) = session.position_at(region.page, x, y, 0.0) {
            assert_eq!(hit.field, "tags.0");
            assert_eq!(hit.granularity, Some(HitGranularity::Cluster));
            if walk.last() != Some(&hit.pos) {
                walk.push(hit.pos);
            }
        }
        x += STEP;
    }

    let expected: Vec<usize> = (0..STAR_TAG.chars().count()).collect();

    // The literal codec lowers `*` to `\*`: two generated bytes, one content
    // char. Content chars only: at the exclusive end `locate` falls back to the
    // segment start, for every codec.
    let mut prev = f32::MIN;
    for &pos in &expected {
        let x = session.locate("tags.0", pos).expect("caret").rect[0];
        assert!(x >= prev, "carets advance left to right at {pos}: {x} < {prev}");
        prev = x;
    }
    assert_eq!(
        walk, expected,
        "one content offset per cluster: an escape resolving to its own interior \
         would repeat, skip, or shift the tail"
    );
}

/// `qm.str` inverts the lowering: whatever the markup escaped, shorthanded or
/// smart-quoted comes back as the value's verbatim text, line breaks included.
#[test]
fn qm_str_projects_a_text_value_to_its_verbatim_string() {
    const ONE: &str = r#"a *b* _c_ "d" it's -- e ... f  g #h $i \j @k <l> // m ~n -1"#;
    const MANY: &str = "first line\n  second, indented\n\nthird";
    let lit = |s: &str| format!("\"{}\"", s.replace('\\', "\\\\").replace('"', "\\\"").replace('\n', "\\n"));
    let temp_dir = TempDir::new().unwrap();
    let quill_path = temp_dir.path().join("str_quill");
    fs::create_dir_all(&quill_path).unwrap();
    fs::write(
        quill_path.join("Quill.yaml"),
        r#"quill:
  name: "str_quill"
  version: "1.0.0"
  backend: "typst"
  description: "qm.str"

typst:
  plate_file: plate.typ

main:
  body:
    enabled: false
  fields:
    one: { type: text }
    many: { type: text, multiline: true }
    blank: { type: text }
    absent: { type: text? }
"#,
    )
    .unwrap();
    fs::write(
        quill_path.join("plate.typ"),
        format!(
            "#import \"@local/quillmark-helper:0.2.0\" as qm\n\
             #assert.eq(qm.str(qm.data.one), {})\n\
             #assert.eq(qm.str(qm.data.many), {})\n\
             #assert.eq(qm.str(qm.data.blank), \"\")\n\
             #assert.eq(qm.str(qm.data.absent), none)\n\
             #set document(author: qm.str(qm.data.one))\n\
             ok\n",
            lit(ONE),
            lit(MANY),
        ),
    )
    .unwrap();
    let quill = quillmark::quill_from_path(&quill_path).expect("load quill");
    let block = |s: &str| s.lines().map(|l| format!("  {l}\n")).collect::<String>();
    let md = format!(
        "~~~card-yaml\n$quill: str_quill\n$kind: main\none: |-\n{}many: |-\n{}blank: \"\"\n~~~\n",
        block(ONE),
        block(MANY),
    );
    let doc = Document::parse(&md).expect("parse").document;
    let session = Engine::new()
        .open(&quill, &doc, common::test_date())
        .expect("the plate's assertions hold");
    assert!(session.page_count() > 0);
}

/// Whitespace at a value's end drops, however many spaces it runs to; at its
/// start it stays.
#[test]
fn qm_str_drops_every_trailing_space() {
    let temp_dir = TempDir::new().unwrap();
    let quill_path = temp_dir.path().join("trail_quill");
    fs::create_dir_all(&quill_path).unwrap();
    fs::write(
        quill_path.join("Quill.yaml"),
        r#"quill:
  name: "trail_quill"
  version: "1.0.0"
  backend: "typst"
  description: "qm.str trailing whitespace"

main:
  body:
    enabled: false
  fields:
    two: { type: text, multiline: true }
    three: { type: text, multiline: true }
    lines: { type: text, multiline: true }
"#,
    )
    .unwrap();
    fs::write(
        quill_path.join("plate.typ"),
        "#import \"@local/quillmark-helper:0.2.0\" as qm\n\
         #assert.eq(qm.str(qm.data.two), \"  trail\")\n\
         #assert.eq(qm.str(qm.data.three), \"trail\")\n\
         #assert.eq(qm.str(qm.data.lines), \"one\\ntwo\")\n\
         ok\n",
    )
    .unwrap();
    let quill = quillmark::quill_from_path(&quill_path).expect("load quill");
    let md = "~~~card-yaml\n$quill: trail_quill\n$kind: main\n\
              two: \"  trail  \"\nthree: \"trail \\t \"\nlines: \"one\\ntwo  \\n  \\n\"\n~~~\n";
    let doc = Document::parse(md).expect("parse").document;
    let session = Engine::new()
        .open(&quill, &doc, common::test_date())
        .expect("the plate's assertions hold");
    assert!(session.page_count() > 0);
}

/// A stored `project: |` block keeps a trailing newline, which a one-line
/// `text` drops: the document validates, renders, and conforms to the line.
#[test]
fn a_one_line_text_written_as_a_block_scalar_renders() {
    let quill = quillmark::quill_from_path(quillmark_fixtures::quills_path("status_report"))
        .expect("load status_report");
    let md = "~~~\n$quill: status_report\nproject: |\n  Harbor Migration\nstate: at_risk\n~~~\n\nBody.\n";
    let mut doc = Document::parse(md).expect("parse").document;
    assert!(quill.validate(&doc).is_empty(), "{:?}", quill.validate(&doc));
    let options = quillmark::RenderOptions::default().with_output_format(quillmark::OutputFormat::Pdf);
    Engine::new()
        .render(&quill, &doc, common::test_date(), &options)
        .expect("renders");
    quill.conform(&mut doc).expect("conforms");
    assert!(doc.to_markdown().contains("\nproject: Harbor Migration\n"), "{}", doc.to_markdown());
}
