//! Advance widths, in thousandths of an em, of each WinAnsi code in the base-14
//! faces a widget draws its value in, from Adobe's Core 14 AFM files.

use crate::FormFont;

impl FormFont {
    /// The advance of WinAnsi `text` set at `size` points.
    pub(crate) fn width(self, text: &[u8], size: f32) -> f32 {
        let units: u32 = match self {
            Self::Courier => 600 * text.len() as u32,
            Self::Helvetica => text.iter().map(|&b| u32::from(HELVETICA[b as usize])).sum(),
            Self::Times => text.iter().map(|&b| u32::from(TIMES[b as usize])).sum(),
        };
        units as f32 * size / 1000.0
    }
}

